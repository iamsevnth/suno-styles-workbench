/**
 * The bass-music, club and rap world: every sub-genre here has its own phrase banks, so a dubstep brief is
 * never described with folk, jazz, rock or lo-fi wording and sibling genres (brostep, deep dubstep, UKG
 * dubstep, riddim) do not read alike. Phrases never state a tempo; the plan owns the BPM.
 */
function edm(
  id: string,
  name: string,
  match: RegExp,
  own: Omit<NativeSub, "id" | "name" | "match" | "edm" | "vocal"> & { vocal?: NativeSub["vocal"] }
): NativeSub {
  return { id, name, match, edm: true, keepWords: true, vocal: "sung", ...own };
}

